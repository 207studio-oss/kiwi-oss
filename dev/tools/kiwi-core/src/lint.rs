//! Rule-source lint and generated rules index (rules/README.md block).
//! Rule metadata has one source: each rules/*.md frontmatter (id, title, date, source, status, summary).
use crate::compiler::frontmatter;
use crate::util::*;
use std::path::Path;

pub const IDX_START: &str = "<!-- kiwi:rules-index:start (generated by `kiwi index`; edit rule frontmatter, not this block) -->";
pub const IDX_END: &str = "<!-- kiwi:rules-index:end -->";
pub const REQUIRED: [&str; 5] = ["id", "date", "source", "status", "summary"];

pub struct RuleFile { pub id: String, pub rel: String, pub fm: std::collections::HashMap<String, String>, pub body: String }

pub fn rule_files(src: &Path) -> Res<Vec<RuleFile>> {
    let mut v: Vec<_> = std::fs::read_dir(src.join("rules")).map_err(e)?.filter_map(|x| x.ok()).map(|x| x.path())
        .filter(|p| p.extension().map(|x| x == "md").unwrap_or(false) && p.file_name().unwrap() != "README.md").collect();
    v.sort();
    v.iter().map(|p| {
        let t = std::fs::read_to_string(p).map_err(e)?;
        let (fm, body) = frontmatter(&t);
        Ok(RuleFile { id: p.file_stem().unwrap().to_string_lossy().into(), rel: format!("rules/{}", p.file_name().unwrap().to_string_lossy()), fm, body })
    }).collect()
}

fn unq(s: &str) -> String { s.trim().trim_matches('"').to_string() }

pub fn render_index(rules: &[RuleFile]) -> String {
    let mut out = vec![IDX_START.to_string(), String::new()];
    for r in rules.iter().filter(|r| r.fm.get("status").map(|s| unq(s) == "active").unwrap_or(true)) {
        let s = r.fm.get("summary").map(|s| unq(s)).unwrap_or_default();
        let d = r.fm.get("date").map(|s| unq(s)).unwrap_or_default();
        let od = if r.fm.get("load").map(|l| unq(l) == "on-demand").unwrap_or(false) { " · on-demand" } else { "" };
        out.push(format!("- [{}.md]({}.md): {} ({}{})", r.id, r.id, s, d, od));
    }
    out.push(String::new()); out.push(IDX_END.to_string());
    out.join("\n")
}

/// Replace (or append) the generated block. Returns new README text.
pub fn apply_index(readme: &str, block: &str) -> String {
    match (readme.find(IDX_START), readme.find(IDX_END)) {
        (Some(a), Some(b)) if b > a => format!("{}{}{}", &readme[..a], block, &readme[b + IDX_END.len()..]),
        _ => format!("{}\n\n{}\n", readme.trim_end(), block),
    }
}

pub fn index(src: &Path, check: bool) -> Res<(serde_json::Value, i32)> {
    let rules = rule_files(src)?;
    let p = src.join("rules/README.md");
    let cur = std::fs::read_to_string(&p).unwrap_or_default();
    let next = apply_index(&cur, &render_index(&rules));
    if check { let ok = cur == next; return Ok((serde_json::json!({"index": if ok {"fresh"} else {"stale"}, "rules": rules.len()}), if ok { 0 } else { 1 })); }
    std::fs::write(&p, next).map_err(e)?;
    Ok((serde_json::json!({"index": "written", "rules": rules.len()}), 0))
}

// ---------------------------------------------------------------- kiwi lint
// errors block the commit (pre-commit hook); warnings are printed only.

fn uuids(t: &str) -> Vec<String> {
    let b = t.as_bytes(); let mut out = vec![]; let mut i = 0;
    let hex = |c: u8| c.is_ascii_digit() || (b'a'..=b'f').contains(&c);
    while i + 36 <= b.len() {
        let s = &b[i..i + 36];
        let ok = s.iter().enumerate().all(|(k, &c)| if [8, 13, 18, 23].contains(&k) { c == b'-' } else { hex(c) });
        let edge = (i == 0 || !hex(b[i - 1])) && (i + 36 == b.len() || !hex(b[i + 36]));
        if ok && edge { out.push(String::from_utf8_lossy(s).to_string()); i += 36; } else { i += 1; }
    }
    out
}

/// "2026-10-21T13:45:00+09:00" → unix seconds (None if unparsable).
pub fn rfc3339(s: &str) -> Option<i64> {
    let s = s.trim(); if s.len() < 19 { return None; }
    let n = |a: usize, b: usize| s.get(a..b)?.parse::<i64>().ok();
    let (y, mo, d, h, mi, se) = (n(0, 4)?, n(5, 7)?, n(8, 10)?, n(11, 13)?, n(14, 16)?, n(17, 19)?);
    let rest = &s[19..]; let rest = rest.trim_start_matches(|c: char| c == '.' || c.is_ascii_digit());
    let off = if rest == "Z" || rest.is_empty() { 0 } else {
        let sign = if rest.starts_with('-') { -1 } else { 1 };
        let hh = rest.get(1..3)?.parse::<i64>().ok()?; let mm = rest.get(4..6)?.parse::<i64>().ok()?; sign * (hh * 3600 + mm * 60) };
    let (yy, mm) = if mo <= 2 { (y - 1, mo + 9) } else { (y, mo - 3) };
    let era = yy.div_euclid(400); let yoe = yy - era * 400; let doy = (153 * mm + 2) / 5 + d - 1;
    let days = era * 146097 + yoe * 365 + yoe / 4 - yoe / 100 + doy - 719468;
    Some(days * 86400 + h * 3600 + mi * 60 + se - off)
}

const FUTURE_TENSE: [&str; 4] = ["로 들어온다", "아직 없다", "나온 뒤 쓴다", "PR 전)"];

pub fn lint(src: &Path, now: i64, changed: &[String]) -> Res<(serde_json::Value, i32)> {
    let mut errors: Vec<String> = vec![]; let mut warnings: Vec<String> = vec![];
    // 1. compile errors (broken links, duplicate ids, missing mandatory)
    let c = crate::compiler::collect(src)?;
    errors.extend(c.errors.iter().cloned()); warnings.extend(c.warnings.iter().cloned());
    // 2. rule frontmatter + H1
    let rules = rule_files(src)?;
    for r in &rules {
        for k in REQUIRED { if r.fm.get(k).map(|v| unq(v).is_empty()).unwrap_or(true) { errors.push(format!("rule_missing_{}:{}", k, r.rel)); } }
        if let Some(id) = r.fm.get("id") { if unq(id) != r.id { errors.push(format!("rule_id_mismatch:{}:{}", r.rel, unq(id))); } }
        if !r.body.lines().any(|l| l.starts_with("# ")) { errors.push(format!("rule_missing_h1:{}", r.rel)); }
        if let Some(s) = r.fm.get("status") { if !["active", "superseded"].contains(&unq(s).as_str()) { errors.push(format!("rule_bad_status:{}:{}", r.rel, unq(s))); } }
        for p in FUTURE_TENSE { if r.body.contains(p) { warnings.push(format!("rule_future_tense:{}:{}", r.rel, p)); } }
    }
    // 3. superseded rules must not be linked from active rules
    let superseded: Vec<&RuleFile> = rules.iter().filter(|r| r.fm.get("status").map(|s| unq(s) == "superseded").unwrap_or(false)).collect();
    for s in &superseded { for r in rules.iter().filter(|r| r.fm.get("status").map(|x| unq(x) == "active").unwrap_or(true)) {
        if r.body.contains(&format!("{}.md", s.id)) { errors.push(format!("links_superseded:{}->{}", r.rel, s.rel)); } } }
    // 4. generated index is fresh
    let readme = std::fs::read_to_string(src.join("rules/README.md")).unwrap_or_default();
    if apply_index(&readme, &render_index(&rules)) != readme { errors.push("rules_index_stale: run `kiwi index --src .`".into()); }
    // 5. agent IDs must be registered (rules/, bots/*.md, kiwi.toml owners, active claims)
    let reg = std::fs::read_to_string(src.join("bots/registry.toml")).unwrap_or_default();
    let known: std::collections::HashSet<String> = uuids(&reg).into_iter().collect();
    if !known.is_empty() {
        let mut scan: Vec<(String, String)> = rules.iter().map(|r| (r.rel.clone(), r.body.clone())).collect();
        if let Ok(t) = std::fs::read_to_string(src.join("kiwi.toml")) { scan.push(("kiwi.toml".into(), t)); }
        for (rel, t) in scan { for u in uuids(&t) { if !known.contains(&u) { errors.push(format!("unregistered_agent_id:{}:{}", rel, u)); } } }
    }
    // 6. active board: claims need a registered agent_id; expired claims must be marked status = "expired"
    if let Ok(rd) = std::fs::read_dir(src.join("bots/active")) {
        let mut v: Vec<_> = rd.filter_map(|x| x.ok()).map(|x| x.path()).filter(|p| p.extension().map(|x| x == "toml").unwrap_or(false)).collect(); v.sort();
        for p in v {
            let rel = format!("bots/active/{}", p.file_name().unwrap().to_string_lossy());
            let t: toml::Value = match std::fs::read_to_string(&p).ok().and_then(|s| s.parse().ok()) { Some(t) => t, None => { errors.push(format!("claim_unparsable:{}", rel)); continue; } };
            let id = t.get("agent_id").and_then(|v| v.as_str()).unwrap_or("");
            if id.is_empty() { errors.push(format!("claim_missing_agent_id:{}", rel)); }
            let status = t.get("status").and_then(|v| v.as_str()).unwrap_or("active");
            if !id.is_empty() && !known.is_empty() && !known.contains(id) && status != "expired" {
                // block new/edited claims by unregistered bots; existing ones are reported until released or marked expired
                let msg = format!("claim_unregistered_agent_id:{}:{}", rel, id);
                if changed.is_empty() || changed.iter().any(|c| c == &rel) { errors.push(msg) } else { warnings.push(msg) }
            }
            if let Some(exp) = t.get("expires").and_then(|v| v.as_str()).and_then(rfc3339) {
                if exp < now && status != "expired" { warnings.push(format!("claim_expired_unmarked:{}", rel)); }
            } else { errors.push(format!("claim_bad_expires:{}", rel)); }
        }
    }
    // 7. mandatory budget
    let mb: usize = c.nodes.iter().filter(|n| n.mandatory && n.kind == "rule").map(|n| n.body.len()).sum();
    if mb > 65536 { errors.push(format!("mandatory_rules_over_budget:{}>65536", mb)); }
    let code = if errors.is_empty() { 0 } else { 1 };
    Ok((serde_json::json!({"lint": if code == 0 {"clean"} else {"failed"}, "errors": errors, "warnings": warnings, "rules": rules.len()}), code))
}
